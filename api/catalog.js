const {
  STOCK_LEN, RAIL_SPEC, BLOCK_SPECS, SERIES_INFO,
  DEFAULT_RAILS, DEFAULT_BLOCKS, DEFAULT_PRICING,
} = require('./_catalog.js');

/**
 * The browser's copy of the catalogue, served at /catalog.js.
 *
 * Dimensions pass through verbatim — they are published Airtac figures and the
 * page needs them to draw and validate. Prices do not: the browser receives a
 * finished rate per rail and a finished price per block, with Airtac list and
 * the markup already multiplied together and left behind on the server.
 *
 * Shipping `list` and `webMarkup` separately, as this file's source still does,
 * handed any reader of view-source the whole pricing formula — list price and
 * the fact that it is multiplied by 2.5. Airtac's list prices are public, so
 * the markup was the part worth protecting, and it was one keystroke away on
 * the same page that deliberately hides a customer's discount percentage.
 *
 * Emitting it from a function rather than committing a derived file keeps one
 * source of truth and no build step: api/_catalog.js stays the only place a
 * price is edited.
 */

function markup(item) {
  return typeof item.markup === 'number'
    ? Math.max(0, item.markup)
    : Math.max(0, DEFAULT_PRICING.webMarkup);
}

/** Usable stock after the standard end allowance — the basis for a per-mm rate. */
function usableFor(series, size) {
  const spec = RAIL_SPEC[series][size];
  return STOCK_LEN - (2 * spec.stdE + DEFAULT_PRICING.buffer);
}

/** Sell rate per mm of rail: list per usable mm, times that part's markup. */
function railRate(rail) {
  return (rail.list / usableFor(rail.series, rail.size)) * (1 + markup(rail) / 100);
}

function blockRate(block) {
  return block.list * (1 + markup(block) / 100);
}

function browserCatalog() {
  return {
    STOCK_LEN,
    RAIL_SPEC,
    BLOCK_SPECS,
    SERIES_INFO,
    // webPerMm / webPrice replace list + markup. The published price is
    // whatever these produce; an account's own rates arrive from /api/customer.
    DEFAULT_RAILS: DEFAULT_RAILS.map(r => ({
      series: r.series, size: r.size, pn: r.pn, webPerMm: railRate(r),
    })),
    DEFAULT_BLOCKS: DEFAULT_BLOCKS.map(b => ({
      family: b.family, type: b.type, size: b.size, pn: b.pn, webPrice: blockRate(b),
    })),
    DEFAULT_PRICING: {
      cutFee: DEFAULT_PRICING.cutFee,
      handling: DEFAULT_PRICING.handling,
      buffer: DEFAULT_PRICING.buffer,
    },
  };
}

function script() {
  const c = browserCatalog();
  const decl = (name, value) => `const ${name} = ${JSON.stringify(value)};`;
  return `/* Generated by api/catalog.js from api/_catalog.js. Do not edit.
   Prices here are final sell figures; Airtac list and the markup behind them
   stay on the server. Edit prices in api/_catalog.js. */
${decl('STOCK_LEN', c.STOCK_LEN)}
${decl('RAIL_SPEC', c.RAIL_SPEC)}
function getSpec(series, size) { return RAIL_SPEC[series]?.[size] || null; }
${decl('BLOCK_SPECS', c.BLOCK_SPECS)}
${decl('SERIES_INFO', c.SERIES_INFO)}
${decl('DEFAULT_RAILS', c.DEFAULT_RAILS)}
${decl('DEFAULT_BLOCKS', c.DEFAULT_BLOCKS)}
${decl('DEFAULT_PRICING', c.DEFAULT_PRICING)}
`;
}

module.exports = async function handler(req, res) {
  res.setHeader('Content-Type', 'application/javascript; charset=utf-8');
  res.setHeader('Cache-Control', 'public, max-age=0, s-maxage=3600, stale-while-revalidate=86400');
  res.status(200).send(script());
};

// Shared with /api/customer, which needs the same rates to build an account's
// table, and with the tests that prove the refactor moved no price.
module.exports.rates = { railRate, blockRate, usableFor, markup, browserCatalog };
